// Generates the TypeScript API types from the committed OpenAPI snapshots in openapi/.
// The snapshots come from the backend code: `python -m scripts.export_openapi` in dummy-app/.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

export const API_NAMES = ["gateway", "controller"] as const;
export type ApiName = (typeof API_NAMES)[number];

export const WEB_ROOT = join(import.meta.dirname, "..");

export function generatedPath(name: ApiName) {
  return join(WEB_ROOT, "src", "api", "generated", `${name}.ts`);
}

export async function generate(name: ApiName): Promise<string> {
  const schema = readFileSync(join(WEB_ROOT, "openapi", `${name}.json`), "utf8");
  const ast = await openapiTS(schema);
  const header = [
    `// Generated by \`npm run gen:api\` from openapi/${name}.json. Do not edit.`,
    "// To update: run `python -m scripts.export_openapi` in dummy-app/, then `npm run gen:api`.",
    "",
  ].join("\n");
  return `${header}\n${astToString(ast)}`;
}
